-- TenderOps AI initial schema (V1). Must run on H2 (PostgreSQL mode) and PostgreSQL 17.
-- No PG-only features. JSON fields are TEXT (Jackson converters in Java).

CREATE TABLE companies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  gst_number VARCHAR(32),
  gst_registered BOOLEAN NOT NULL DEFAULT FALSE,
  msme_registered BOOLEAN NOT NULL DEFAULT FALSE,
  blacklisted BOOLEAN NOT NULL DEFAULT FALSE,
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  data_version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  email VARCHAR(320) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','BID_MANAGER','VIEWER')),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_users_company ON users(company_id);

CREATE TABLE company_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  file_name VARCHAR(255) NOT NULL,
  storage_path VARCHAR(512) NOT NULL,
  sha256 CHAR(64) NOT NULL,
  mime_type VARCHAR(128) NOT NULL,
  size_bytes BIGINT NOT NULL,
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_company_documents_company ON company_documents(company_id);

CREATE TABLE company_financial_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  fy_label VARCHAR(16) NOT NULL,
  fy_end_date DATE NOT NULL,
  turnover NUMERIC(19,4),
  net_worth NUMERIC(19,4),
  currency VARCHAR(8) NOT NULL DEFAULT 'INR',
  is_audited BOOLEAN NOT NULL,
  document_id BIGINT REFERENCES company_documents(id),
  UNIQUE (company_id, fy_label)
);

CREATE TABLE company_projects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  name VARCHAR(255) NOT NULL,
  contract_value NUMERIC(19,4),
  currency VARCHAR(8) NOT NULL DEFAULT 'INR',
  status VARCHAR(20) NOT NULL,
  completion_date DATE,
  domain_category VARCHAR(32) NOT NULL,
  work_order_doc_id BIGINT REFERENCES company_documents(id),
  completion_cert_doc_id BIGINT REFERENCES company_documents(id)
);
CREATE INDEX idx_company_projects_company ON company_projects(company_id);

CREATE TABLE company_certificates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  name VARCHAR(64) NOT NULL,
  level_text VARCHAR(32),
  level_number INTEGER,
  issue_date DATE,
  expiry_date DATE,
  amount NUMERIC(19,4),
  currency VARCHAR(8) NOT NULL DEFAULT 'INR',
  document_id BIGINT REFERENCES company_documents(id)
);
CREATE INDEX idx_company_certificates_company ON company_certificates(company_id);

CREATE TABLE tenders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  title VARCHAR(512) NOT NULL,
  reference VARCHAR(128),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_tenders_company ON tenders(company_id);

CREATE TABLE tender_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tender_id BIGINT NOT NULL REFERENCES tenders(id),
  version_number INTEGER NOT NULL,
  kind VARCHAR(16) NOT NULL CHECK (kind IN ('BASE','CORRIGENDUM','FULL_REVISION')),
  sha256 CHAR(64) NOT NULL,
  storage_path VARCHAR(512) NOT NULL,
  page_count INTEGER NOT NULL,
  reference VARCHAR(128),
  estimated_value NUMERIC(19,4),
  emd_amount NUMERIC(19,4),
  tender_fee NUMERIC(19,4),
  submission_deadline TIMESTAMP WITH TIME ZONE,
  UNIQUE (tender_id, version_number)
);
CREATE INDEX idx_tender_versions_tender ON tender_versions(tender_id);

CREATE TABLE document_pages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tender_version_id BIGINT NOT NULL REFERENCES tender_versions(id),
  page_no INTEGER NOT NULL,
  text_content TEXT,
  classification VARCHAR(16) NOT NULL CHECK (classification IN ('DIGITAL_TEXT','SCANNED','MIXED')),
  needs_human_review BOOLEAN NOT NULL DEFAULT FALSE,
  review_reason VARCHAR(64),
  rendered_path VARCHAR(512),
  image_width INTEGER,
  image_height INTEGER,
  extraction_confidence NUMERIC(5,4),
  UNIQUE (tender_version_id, page_no)
);

CREATE TABLE visual_regions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id BIGINT NOT NULL REFERENCES document_pages(id),
  region_type VARCHAR(32) NOT NULL CHECK (region_type IN ('OFFICIAL_STAMP','HANDWRITTEN_SIGNATURE','TABLE_REGION')),
  x0 NUMERIC(8,6) NOT NULL,
  y0 NUMERIC(8,6) NOT NULL,
  x1 NUMERIC(8,6) NOT NULL,
  y1 NUMERIC(8,6) NOT NULL,
  mask_ref TEXT,
  confidence NUMERIC(5,4) NOT NULL,
  source VARCHAR(24) NOT NULL CHECK (source IN ('SAM_3_1','FALLBACK_HEURISTIC')),
  crop_path VARCHAR(512),
  region_text TEXT,
  structured_table TEXT,
  content_source VARCHAR(24) CHECK (content_source IN ('MUSE_VISION','PDFBOX_GEOMETRIC'))
);
CREATE INDEX idx_visual_regions_page ON visual_regions(page_id);

CREATE TABLE tender_requirements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tender_version_id BIGINT NOT NULL REFERENCES tender_versions(id),
  clause_ref VARCHAR(32) NOT NULL,
  category VARCHAR(64) NOT NULL,
  mandatory BOOLEAN NOT NULL DEFAULT TRUE,
  mandatory_ambiguous BOOLEAN NOT NULL DEFAULT FALSE,
  metric VARCHAR(48) NOT NULL,
  operator VARCHAR(8) NOT NULL CHECK (operator IN ('GTE','GT','LTE','LT','EQ')),
  amount_text VARCHAR(128),
  amount_value NUMERIC(19,4),
  currency VARCHAR(8) NOT NULL DEFAULT 'INR',
  count_value INTEGER,
  lookback_years INTEGER,
  domain_tags VARCHAR(256),
  certificate_name VARCHAR(64),
  certificate_level INTEGER,
  condition_tree TEXT,
  source_document VARCHAR(512) NOT NULL,
  source_page INTEGER NOT NULL,
  source_region_id BIGINT REFERENCES visual_regions(id),
  original_quote TEXT NOT NULL,
  quote_verified BOOLEAN NOT NULL,
  confidence NUMERIC(5,4),
  fingerprint CHAR(64) NOT NULL,
  amendment_action VARCHAR(16),
  target_clause_ref VARCHAR(32)
);
CREATE INDEX idx_tender_requirements_version ON tender_requirements(tender_version_id);

CREATE TABLE compliance_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tender_version_id BIGINT NOT NULL REFERENCES tender_versions(id),
  company_id BIGINT NOT NULL REFERENCES companies(id),
  company_data_version BIGINT NOT NULL,
  evaluation_context_hash CHAR(64) NOT NULL,
  rule_version VARCHAR(16) NOT NULL,
  muse_mode VARCHAR(16) NOT NULL CHECK (muse_mode IN ('LIVE','FALLBACK')),
  sam_mode VARCHAR(16) NOT NULL CHECK (sam_mode IN ('LIVE','FALLBACK')),
  readiness_score NUMERIC(6,2),
  decision VARCHAR(24),
  started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finished_at TIMESTAMP WITH TIME ZONE,
  time_saved_percent NUMERIC(6,2),
  manual_minutes NUMERIC(10,2),
  assisted_minutes NUMERIC(10,2),
  summary_text TEXT,
  grounding_warning BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_compliance_runs_version ON compliance_runs(tender_version_id);

CREATE TABLE compliance_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES compliance_runs(id),
  requirement_id BIGINT NOT NULL REFERENCES tender_requirements(id),
  verdict VARCHAR(16) NOT NULL CHECK (verdict IN ('PASS','FAIL','UNKNOWN','NEEDS_REVIEW')),
  reason_code VARCHAR(64),
  calculation_trace TEXT NOT NULL,
  copied_from_run_id BIGINT REFERENCES compliance_runs(id)
);
CREATE INDEX idx_compliance_results_run ON compliance_results(run_id);

CREATE TABLE risk_findings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES compliance_runs(id),
  severity VARCHAR(16) NOT NULL CHECK (severity IN ('CRITICAL','HIGH','MEDIUM','LOW')),
  risk_code VARCHAR(64) NOT NULL,
  source_clause VARCHAR(32),
  evidence_summary TEXT,
  detection_reason TEXT,
  business_impact TEXT,
  corrective_action TEXT
);
CREATE INDEX idx_risk_findings_run ON risk_findings(run_id);

CREATE TABLE bid_decisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES compliance_runs(id),
  recommendation VARCHAR(24) NOT NULL,
  approval_status VARCHAR(32) NOT NULL,
  approved_by BIGINT REFERENCES users(id),
  approved_at TIMESTAMP WITH TIME ZONE,
  warnings TEXT
);

CREATE TABLE amendments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tender_id BIGINT NOT NULL REFERENCES tenders(id),
  base_version_id BIGINT NOT NULL REFERENCES tender_versions(id),
  new_version_id BIGINT NOT NULL REFERENCES tender_versions(id),
  diff_json TEXT NOT NULL,
  prev_decision VARCHAR(24),
  new_decision VARCHAR(24),
  score_delta NUMERIC(6,2)
);

CREATE TABLE agent_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES compliance_runs(id),
  requirement_id BIGINT REFERENCES tender_requirements(id),
  mode VARCHAR(32) NOT NULL,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finished_at TIMESTAMP WITH TIME ZONE,
  final_verdict VARCHAR(16)
);

CREATE TABLE agent_steps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  agent_run_id BIGINT NOT NULL REFERENCES agent_runs(id),
  step_no INTEGER NOT NULL,
  tool_name VARCHAR(64) NOT NULL,
  input_json TEXT,
  output_json TEXT,
  latency_ms BIGINT,
  error_text TEXT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE workflow_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tender_version_id BIGINT NOT NULL REFERENCES tender_versions(id),
  company_id BIGINT NOT NULL REFERENCES companies(id),
  status VARCHAR(16) NOT NULL CHECK (status IN ('QUEUED','RUNNING','COMPLETED','FAILED')),
  current_stage VARCHAR(16),
  progress_json TEXT,
  attempt INTEGER NOT NULL DEFAULT 0,
  error_text TEXT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  finished_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_workflow_jobs_version ON workflow_jobs(tender_version_id);

CREATE TABLE workflow_events (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tender_version_id BIGINT NOT NULL REFERENCES tender_versions(id),
  company_id BIGINT NOT NULL REFERENCES companies(id),
  type VARCHAR(32) NOT NULL,
  stage VARCHAR(16),
  payload TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_workflow_events_version_seq ON workflow_events(tender_version_id, seq);
CREATE INDEX idx_workflow_events_company ON workflow_events(company_id, seq);

CREATE TABLE ai_call_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT REFERENCES compliance_runs(id),
  component VARCHAR(16) NOT NULL,
  model VARCHAR(64) NOT NULL,
  purpose VARCHAR(128) NOT NULL,
  status VARCHAR(24) NOT NULL,
  attempt INTEGER NOT NULL DEFAULT 1,
  latency_ms BIGINT,
  ai_mode VARCHAR(16) NOT NULL,
  error_text TEXT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT REFERENCES companies(id),
  user_id BIGINT REFERENCES users(id),
  action VARCHAR(128) NOT NULL,
  entity_type VARCHAR(64) NOT NULL,
  entity_id BIGINT,
  before_json TEXT,
  after_json TEXT,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_audit_logs_company ON audit_logs(company_id, id);
